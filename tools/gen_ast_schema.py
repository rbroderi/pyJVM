"""Generate runtime/pyjvm315/parser/AstSchema.java from the reference interpreter's `ast` module.

Run with the newest supported CPython (python3.15): the table is a superset of older versions.
Field encoding: name, '*' suffix = list, '?' suffix = optional.
"""
from __future__ import annotations

import ast
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "runtime/pyjvm315/parser/AstSchema.java"
ABSTRACT = {"AST", "mod", "stmt", "expr", "expr_context", "boolop", "operator", "unaryop", "cmpop",
            "excepthandler", "pattern", "type_ignore", "type_param"}


def kind(field: str, types: dict) -> str:
    t = str(types.get(field, ""))
    return field + ("*" if t.startswith("list[") else "?" if "None" in t else "")


def main() -> None:
    rows = []
    for name in sorted(dir(ast)):
        cls = getattr(ast, name)
        if not (isinstance(cls, type) and issubclass(cls, ast.AST)) or name in ABSTRACT or name.startswith("_"):
            continue
        if cls.__module__ != "ast" and name not in vars(ast):
            continue
        base = cls.__mro__[1].__name__
        types = getattr(cls, "_field_types", {})
        fields = [kind(f, types) for f in cls._fields]
        has_pos = "lineno" in cls._attributes
        rows.append((name, base, has_pos, fields))
    lines = ["// SPDX-License-Identifier: GPL-3.0-or-later WITH AdditionRef-pyJVM-Linking-Exception", "package pyjvm315.parser;", "", "/** GENERATED by tools/gen_ast_schema.py from CPython %d.%d's ast module. Do not edit. */"
             % sys.version_info[:2], "final class AstSchema {", "    private AstSchema() {}",
             "    /** name, base, hasPositions('1'/'0'), then fields (suffix * = list, ? = optional). */",
             "    static final String[][] NODES = {"]
    for name, base, pos, fields in rows:
        items = ", ".join('"%s"' % x for x in (name, base, "1" if pos else "0", *fields))
        lines.append("        {%s}," % items)
    lines += ["    };", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(rows)} node types -> {OUT}")


if __name__ == "__main__":
    main()
