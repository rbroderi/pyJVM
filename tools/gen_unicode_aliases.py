"""Generate runtime/pyjvm315/parser/UnicodeAliases.java: \\N{...} aliases that java.lang.Character lacks.

Candidates are the standard control/format-character aliases; each is verified against the reference
interpreter's unicodedata before being written, so the table can only contain correct entries.
"""
from __future__ import annotations

import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "runtime/pyjvm315/parser/UnicodeAliases.java"
C0 = ["NULL|NUL", "START OF HEADING|SOH", "START OF TEXT|STX", "END OF TEXT|ETX", "END OF TRANSMISSION|EOT", "ENQUIRY|ENQ",
      "ACKNOWLEDGE|ACK", "ALERT|BEL", "BACKSPACE|BS", "CHARACTER TABULATION|HORIZONTAL TABULATION|HT|TAB",
      "LINE FEED|NEW LINE|END OF LINE|LF|NL|EOL", "LINE TABULATION|VERTICAL TABULATION|VT", "FORM FEED|FF", "CARRIAGE RETURN|CR",
      "SHIFT OUT|LOCKING-SHIFT ONE|SO", "SHIFT IN|LOCKING-SHIFT ZERO|SI", "DATA LINK ESCAPE|DLE", "DEVICE CONTROL ONE|DC1",
      "DEVICE CONTROL TWO|DC2", "DEVICE CONTROL THREE|DC3", "DEVICE CONTROL FOUR|DC4", "NEGATIVE ACKNOWLEDGE|NAK",
      "SYNCHRONOUS IDLE|SYN", "END OF TRANSMISSION BLOCK|ETB", "CANCEL|CAN", "END OF MEDIUM|EOM", "SUBSTITUTE|SUB",
      "ESCAPE|ESC", "INFORMATION SEPARATOR FOUR|FILE SEPARATOR|FS", "INFORMATION SEPARATOR THREE|GROUP SEPARATOR|GS",
      "INFORMATION SEPARATOR TWO|RECORD SEPARATOR|RS", "INFORMATION SEPARATOR ONE|UNIT SEPARATOR|US"]
C1 = {0x80: "PADDING CHARACTER|PAD", 0x81: "HIGH OCTET PRESET|HOP", 0x82: "BREAK PERMITTED HERE|BPH", 0x83: "NO BREAK HERE|NBH",
      0x84: "INDEX|IND", 0x85: "NEXT LINE|NEL", 0x86: "START OF SELECTED AREA|SSA", 0x87: "END OF SELECTED AREA|ESA",
      0x88: "CHARACTER TABULATION SET|HORIZONTAL TABULATION SET|HTS",
      0x89: "CHARACTER TABULATION WITH JUSTIFICATION|HORIZONTAL TABULATION WITH JUSTIFICATION|HTJ",
      0x8A: "LINE TABULATION SET|VERTICAL TABULATION SET|VTS", 0x8B: "PARTIAL LINE FORWARD|PARTIAL LINE DOWN|PLD",
      0x8C: "PARTIAL LINE BACKWARD|PARTIAL LINE UP|PLU", 0x8D: "REVERSE LINE FEED|REVERSE INDEX|RI",
      0x8E: "SINGLE SHIFT TWO|SINGLE-SHIFT-2|SS2", 0x8F: "SINGLE SHIFT THREE|SINGLE-SHIFT-3|SS3", 0x90: "DEVICE CONTROL STRING|DCS",
      0x91: "PRIVATE USE ONE|PRIVATE USE-1|PU1", 0x92: "PRIVATE USE TWO|PRIVATE USE-2|PU2", 0x93: "SET TRANSMIT STATE|STS",
      0x94: "CANCEL CHARACTER|CCH", 0x95: "MESSAGE WAITING|MW", 0x96: "START OF GUARDED AREA|START OF PROTECTED AREA|SPA",
      0x97: "END OF GUARDED AREA|END OF PROTECTED AREA|EPA", 0x98: "START OF STRING|SOS",
      0x99: "SINGLE GRAPHIC CHARACTER INTRODUCER|SGC", 0x9A: "SINGLE CHARACTER INTRODUCER|SCI", 0x9B: "CONTROL SEQUENCE INTRODUCER|CSI",
      0x9C: "STRING TERMINATOR|ST", 0x9D: "OPERATING SYSTEM COMMAND|OSC", 0x9E: "PRIVACY MESSAGE|PM",
      0x9F: "APPLICATION PROGRAM COMMAND|APC"}
OTHER = {0x20: "SP", 0x7F: "DELETE|DEL", 0xA0: "NBSP", 0xAD: "SHY", 0x34F: "CGJ", 0x61C: "ALM", 0x180E: "MVS", 0x200B: "ZWSP",
         0x200C: "ZWNJ", 0x200D: "ZWJ", 0x200E: "LRM", 0x200F: "RLM", 0x202A: "LRE", 0x202B: "RLE", 0x202C: "PDF", 0x202D: "LRO",
         0x202E: "RLO", 0x202F: "NNBSP", 0x205F: "MMSP", 0x2060: "WJ", 0x2066: "LRI", 0x2067: "RLI", 0x2068: "FSI", 0x2069: "PDI",
         0xFEFF: "BYTE ORDER MARK|BOM|ZWNBSP"}


def main() -> None:
    cand: dict[int, list[str]] = {}
    for cp, names in enumerate(C0):
        cand[cp] = names.split("|")
    for cp, names in {**C1, **OTHER}.items():
        cand.setdefault(cp, []).extend(names.split("|"))
    for k in range(1, 17):
        cand[0xFE00 + k - 1] = [f"VARIATION SELECTOR-{k}", f"VS{k}"]
    for k in range(17, 257):
        cand[0xE0100 + k - 17] = [f"VARIATION SELECTOR-{k}", f"VS{k}"]
    entries = []
    rejected = []
    for cp, names in sorted(cand.items()):
        for name in names:
            try:
                ok = ord(unicodedata.lookup(name)) == cp
            except KeyError:
                ok = False
            (entries if ok else rejected).append((name, cp))
    chunks, cur = [], []
    for name, cp in entries:
        cur.append(f"{name}={cp:X}")
        if len(cur) == 40:
            chunks.append(";".join(cur)); cur = []
    if cur:
        chunks.append(";".join(cur))
    lines = ["// SPDX-License-Identifier: GPL-3.0-or-later WITH AdditionRef-pyJVM-Linking-Exception", "package pyjvm315.parser;", "", "import java.util.HashMap;", "import java.util.Map;", "",
             "/** GENERATED by tools/gen_unicode_aliases.py; \\N{...} aliases verified against CPython's unicodedata. */",
             "final class UnicodeAliases {", "    private UnicodeAliases() {}", "    static final Map<String, Integer> BY_NAME = new HashMap<>();",
             "    // data, not code: the table stays out of the JVM's huge-method limit", "    private static final String[] DATA = {"]
    lines += [f'        "{c}",' for c in chunks]
    lines += ["    };", "    static {", "        for (String chunk : DATA)", "            for (String entry : chunk.split(\";\")) {",
              "                int eq = entry.lastIndexOf('=');", "                BY_NAME.put(entry.substring(0, eq), Integer.parseInt(entry.substring(eq + 1), 16));",
              "            }", "    }", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(entries)} verified aliases, {len(rejected)} rejected")


if __name__ == "__main__":
    main()
