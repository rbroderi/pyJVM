def show(label, fn):
    try:
        r = fn()
        print(label, "->", repr(r))
    except BaseException as e:
        extra = ""
        if isinstance(e, OSError):
            extra = " errno=%r filename=%r filename2=%r" % (e.errno, e.filename, e.filename2)
        print(label, "-> EXC", type(e).__name__ + ":", str(e).replace(D, "<tmp>"), extra.replace(D, "<tmp>"))

